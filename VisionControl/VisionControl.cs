                    return;
                }
            }
            else
            {
                try
                {
                    if (hikGrabThread != null)
                    {
                        hikCanGrab = false;
                        hikGrabThread.Join();  // 主线程阻塞，等待线程结束
                                               //      hIKVisionCamera.StopGrabbing();  // 停止采集  

                    }
                }
                catch
                {

                }
            }
