        public void OpenOrCloseCam(bool bOpen)
        {
            if (bOpen)
            {
                if (hikGrabThread != null && hikGrabThread.IsAlive)
                    return;
                try
                {

                    // 用线程更新显示
                    hikCanGrab = true;
                    hikGrabThread = new Thread(GrabThreadProcess);
                    hikGrabThread.Start();
                }
                catch
                {
                    hikCanGrab = false;
